"""Shared helpers for the Chaord reference-data package (bench/reference).

This module and everything it imports MUST NOT import chaord: reference
data is generated by an independent MD engine (ASE) so that it can be used
to validate chaord itself (circular-validation ban, see AGENTS.md).

Contents:
  * frame I/O in the bench npz convention (r, L, symbols U8)
  * species-pair radial distribution g(r) and minimum-pair distances
  * the generic physical-sanity evaluator driven by provenance.json
    (density, minimum pair distances, first g(r) peak windows, frame
    distinctness) used by check_sanity.py.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.spatial import cKDTree

FRAME_KEYS = ("r", "L", "symbols")
N_FRAMES_MIN = 5


# --------------------------------------------------------------------- io --

def save_frame(path: Path, pos: np.ndarray, L: np.ndarray, symbols) -> None:
    """Write one frame in the bench npz convention."""
    pos = np.asarray(np.mod(pos, L), dtype=np.float64)
    np.savez(path, r=pos, L=np.asarray(L, dtype=np.float64),
             symbols=np.array(list(symbols), dtype="U8"))


def load_frame(path: Path):
    with np.load(path) as z:
        for k in FRAME_KEYS:
            if k not in z:
                raise ValueError(f"{path.name}: missing array {k!r}")
        return (np.asarray(z["r"], float), np.asarray(z["L"], float),
                [str(s) for s in z["symbols"]])


def load_case_frames(case_dir: Path):
    frames = []
    for k in range(N_FRAMES_MIN):
        p = case_dir / f"frame_{k}.npz"
        if not p.is_file():
            break
        frames.append(load_frame(p))
    return frames


def load_provenance(case_dir: Path) -> dict:
    return json.loads((case_dir / "provenance.json").read_text(encoding="utf-8"))


# ------------------------------------------------------------------ probes --

def _selection_mask(symbols, elements):
    """Boolean mask of atoms whose symbol is in `elements` (literal symbols;
    'X' is the LJ reference species, not a wildcard)."""
    if not elements:
        return np.ones(len(symbols), bool)
    return np.array([s in elements for s in symbols])


def pair_histogram(cross_tree_a, cross_tree_b, n_a, n_b, volume, rmax, bins):
    """Pair-count histogram -> g(r) between two selections under PBC.

    count_neighbors is cumulative, so the r=0 self pairs (identical trees)
    fall on the first edge and are dropped by the diff."""
    edges = np.linspace(0.0, rmax, bins + 1)
    counts = cross_tree_a.count_neighbors(cross_tree_b, edges)
    h = np.diff(counts).astype(float)
    shell = 4.0 / 3.0 * np.pi * (edges[1:] ** 3 - edges[:-1] ** 3)
    rho_a = n_a / volume
    # identical trees count each unordered pair twice (both directions),
    # which is exactly the factor g(r) needs; cross trees count once
    return h / (n_b * rho_a * shell), 0.5 * (edges[1:] + edges[:-1])


def pair_gr(pos, symbols, L, elements, rmax, bins):
    """g(r) of the species pair `elements` (['X'] or ['X','X'] = all atoms)."""
    ma = _selection_mask(symbols, elements[:1])
    mb = _selection_mask(symbols, elements[1:] or elements[:1])
    la = np.mod(pos[ma], L)
    lb = np.mod(pos[mb], L)
    ta = cKDTree(la, boxsize=L)
    tb = cKDTree(lb, boxsize=L)
    vol = float(np.prod(L))
    return pair_histogram(ta, tb, ma.sum(), mb.sum(), vol, rmax, bins)


def min_pair_distance(pos, symbols, L, elements_a, elements_b=None,
                      exclude_bonded=None):
    """Minimum distance between the two species selections (PBC-aware).

    exclude_bonded: optional (n_atoms,) integer molecule id; pairs sharing a
    non-negative id are skipped (rigid-water intramolecular pairs)."""
    ma = _selection_mask(symbols, [elements_a])
    same = elements_b is None or elements_b == elements_a
    mb = ma if same else _selection_mask(symbols, [elements_b])
    la = np.mod(pos[ma], L)
    lb = np.mod(pos[mb], L)
    ta = cKDTree(la, boxsize=L)
    tb = cKDTree(lb, boxsize=L)
    if same:
        pairs = ta.query_pairs(6.0, output_type="ndarray")
    else:
        idx = ta.query_ball_tree(tb, 6.0)
        pairs = np.array([[a, b] for a, bs in enumerate(idx) for b in bs],
                         dtype=int).reshape(-1, 2)
    if exclude_bonded is not None and len(pairs):
        ida = exclude_bonded[ma][pairs[:, 0]]
        idb = exclude_bonded[mb][pairs[:, 1]]
        keep = ~(ida >= 0) | (ida != idb)
        pairs = pairs[keep]
    if not len(pairs):
        return float("inf")
    d = lb[pairs[:, 1]] - la[pairs[:, 0]]
    d -= L * np.round(d / L)
    return float(np.sqrt((d * d).sum(1)).min())


def first_peak_position(pos, symbols, L, elements, window, rmax, bins=220):
    """Position of the tallest g(r) maximum in [0.6*lo, 1.4*hi]."""
    g, rm = pair_gr(pos, symbols, L, elements, rmax, bins)
    lo, hi = window
    m = (rm >= 0.6 * lo) & (rm <= 1.4 * hi)
    if not m.any() or g[m].max() <= 0:
        return float("nan")
    return float(rm[m][int(np.argmax(g[m]))])


def region_density(pos, L, z_lo, z_hi):
    """Number density of all atoms with z in [z_lo, z_hi] (per A^3 or sigma^3)."""
    z = np.mod(pos[:, 2], L[2])
    n = int(((z >= z_lo) & (z < z_hi)).sum())
    return n / ((z_hi - z_lo) * L[0] * L[1])


def frames_all_distinct(frames):
    for i in range(len(frames)):
        for j in range(i + 1, len(frames)):
            if np.array_equal(frames[i][0], frames[j][0]):
                return False
    return True


# ------------------------------------------------------------- sanity eval --

def evaluate_case(case_dir: Path) -> dict:
    """Run the recorded sanity checks of one case; returns a report dict."""
    prov = load_provenance(case_dir)
    frames = load_case_frames(case_dir)
    report = {"case": prov.get("case", case_dir.name), "checks": {},
              "n_frames": len(frames), "passed": False}

    def record(name, passed, detail):
        report["checks"][name] = {"pass": bool(passed), **detail}

    ok = len(frames) >= N_FRAMES_MIN
    record("frames", ok, {"n_frames": len(frames)})

    if frames:
        ok = frames_all_distinct(frames)
        record("frames_distinct", ok,
               {"note": "no two frames share identical coordinates"})

    san = prov.get("sanity", {})

    # density (whole box, or per region for the interface cases)
    for spec in san.get("density", [{}]) if san.get("density") else []:
        name = spec.get("region", "bulk")
        meas = []
        for r, L, _ in frames:
            if "z" in spec:
                meas.append(region_density(r, L, spec["z"][0], spec["z"][1]))
            else:
                meas.append(len(r) / float(np.prod(L)))
        target = spec["target"]
        tol = spec["tolerance_pct"] / 100.0
        # reduced-unit targets are recorded as rho*; convert case by case via
        # the same convention the generator used: target < 1 in sigma units
        dev = max(abs(m - target) / target for m in meas)
        record(f"density:{name}", dev <= tol,
               {"measured": [round(m, 6) for m in meas], "target": target,
                "max_rel_dev_pct": round(dev * 100, 3),
                "tolerance_pct": spec["tolerance_pct"]})

    # minimum pair distances
    for spec in san.get("min_pairs", []):
        meas = []
        excl = None
        for r, L, s in frames:
            if spec.get("exclude_intramolecular"):
                # rebuild molecule ids: consecutive O,H,H triples are water
                ids = np.full(len(s), -1)
                k = 0
                for i, sym in enumerate(s):
                    if sym == "O":
                        ids[i:i + 3] = k
                        k += 1
                excl = ids
            meas.append(min_pair_distance(
                r, s, L, spec["elements"][0],
                spec["elements"][1] if len(spec["elements"]) > 1 else None,
                exclude_bonded=excl))
        ok = all(m >= spec["floor"] for m in meas)
        record("min_pair:" + "-".join(spec["elements"]), ok,
               {"measured_min": round(min(meas), 4), "floor": spec["floor"],
                "note": spec.get("note", "")})

    # g(r) first-peak windows
    for spec in san.get("gr_peaks", []):
        meas = []
        for r, L, s in frames:
            sel = np.mod(r[:, 2], L[2])
            if "z" in spec:
                m = (sel >= spec["z"][0]) & (sel < spec["z"][1])
                pr = r[m]
                sy = [sym for sym, keep in zip(s, m) if keep]
            else:
                pr, sy = r, s
            meas.append(first_peak_position(pr, sy, L, spec["elements"],
                                            spec["window"], spec["rmax"]))
        lo, hi = spec["window"]
        ok = all(lo <= m <= hi for m in meas)
        record("gr_peak:" + "-".join(spec["elements"]) +
               ("@" + spec["region"] if "region" in spec else ""), ok,
               {"measured": [round(m, 4) for m in meas],
                "window": spec["window"],
                "note": spec.get("note", "")})

    report["passed"] = all(c["pass"] for c in report["checks"].values())
    return report
